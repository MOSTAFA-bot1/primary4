// Helper functions
function getAllVocabulary() {
    const all = [];
    for (const unitNum in vocabularyData) {
        const unit = vocabularyData[unitNum];
        for (const lessonNum in unit.lessons) {
            const lesson = unit.lessons[lessonNum];
            lesson.words.forEach(item => {
                all.push({
                    word: item.word,
                    meaning: item.meaning,
                    unit: parseInt(unitNum),
                    unitName: unit.name,
                    lesson: parseInt(lessonNum),
                    lessonName: lesson.name
                });
            });
        }
    }
    return all;
}

function getUnitVocabulary(unitNum) {
    const unit = vocabularyData[unitNum];
    if (!unit) return [];
    const result = [];
    for (const lessonNum in unit.lessons) {
        const lesson = unit.lessons[lessonNum];
        lesson.words.forEach(item => {
            result.push({
                word: item.word,
                meaning: item.meaning,
                lesson: parseInt(lessonNum),
                lessonName: lesson.name
            });
        });
    }
    return result;
}

function getLessonVocabulary(unitNum, lessonNum) {
    const unit = vocabularyData[unitNum];
    if (!unit || !unit.lessons[lessonNum]) return [];
    return unit.lessons[lessonNum].words.map(item => ({
        word: item.word,
        meaning: item.meaning
    }));
}

function getUnitLessons(unitNum) {
    const unit = vocabularyData[unitNum];
    if (!unit) return [];
    return Object.keys(unit.lessons).map(lessonNum => ({
        number: parseInt(lessonNum),
        name: unit.lessons[lessonNum].name,
        wordCount: unit.lessons[lessonNum].words.length
    }));
}

function getAllUnitsSummary() {
    const summary = [];
    for (const unitNum in vocabularyData) {
        const unit = vocabularyData[unitNum];
        let totalWords = 0;
        const lessons = [];
        for (const lessonNum in unit.lessons) {
            const count = unit.lessons[lessonNum].words.length;
            totalWords += count;
            lessons.push({
                number: parseInt(lessonNum),
                name: unit.lessons[lessonNum].name,
                wordCount: count
            });
        }
        summary.push({
            number: parseInt(unitNum),
            name: unit.name,
            lessonCount: Object.keys(unit.lessons).length,
            totalWords: totalWords,
            lessons: lessons
        });
    }
    return summary;
}

